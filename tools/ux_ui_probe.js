(async () => {
  const results = {};
  const check = (key, value) => {
    results[key] = !!value;
    if (!value) throw Error(key);
  };
  const tick = () => new Promise(resolve => setTimeout(resolve, 30));
  const change = (id, value) => {
    const node = $(id);
    if (node.type === "checkbox") node.checked = value;
    else node.value = value;
    node.dispatchEvent(new Event("change", { bubbles: true }));
  };
  try {
    for (let attempt = 0; attempt < 150 && (!studioState.project || !$('projectSettingsButton')); attempt++) await tick();
    await refresh();
    const originalJobs = JSON.stringify(studioState.snapshot.jobs.map(job => [job.id, job.state, job.provider, job.done]));
    showView("home");
    const dialog = $("projectSettingsDialog");
    check("settingsAreProjectScoped", !!dialog && !dialog.open && !document.querySelector(".right").contains($("context")));
    check("rareControlsAwayFromWorkspace", dialog.contains($("endpoint")) && $("updatesDialog").contains($("closePrefsMenu")) && dialog.contains($("importButton")));
    check("navigationGrouped", $("workspaceNavigation").contains($("viewAll")) && $("workspaceNavigation").contains($("errorsButton")));
    check("localDefaultHasNoCloudChoice", ![...$("executionModel").options].some(option => option.value === "cloud"));
    check("perRunLimitsBesideTask", $("taskCard").contains($("newRunLimits")) && !dialog.contains($("newRunLimits")));
    $("projectSettingsButton").click();
    check("projectSettingsOpen", dialog.open && dialog.querySelectorAll('[role="tab"]').length === 5);
    check("onlySelectedPanelVisible", [...dialog.querySelectorAll('[role="tabpanel"]')].filter(panel => !panel.hidden).length === 1);
    const source = $("source_language").value;
    change("source_language", "French");
    $("cancelProjectSettings").click();
    await tick();
    check("cancelRestoresDraft", !dialog.open && $("source_language").value === source);
    $("projectSettingsButton").click();
    change("source_language", "Japanese");
    dialog.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true, cancelable: true }));
    await tick();
    check("escapeRestoresDraft", !dialog.open && $("source_language").value === source);
    $("projectSettingsButton").click();
    $("settingsTab-context").click();
    const contextNode = $("context_before");
    change("context_before", 9);
    await refresh();
    check("pollPreservesSettingsEditor", contextNode === $("context_before") && contextNode.value === "9" && !$("settingsPanel-context").hidden);
    change("use_project_knowledge", false);
    check("dependentMemoryControls", $("analyze_before_translate").closest(".ux-toggle").hidden && !$("analyze_before_translate").checked && $("analyzeKnowledge").disabled);
    $("settingsTab-integrations").click();
    change("cloud_enabled", true);
    check("cloudRequiresExplicitOptIn", [...$("executionModel").options].some(option => option.value === "cloud") && !cloudConnection.hidden);
    change("cloud_model", "venice-uncensored-1-2");
    $("executionModel").value = "cloud";
    $("executionModel").dispatchEvent(new Event("change", { bubbles: true }));
    check("cloudSelectionWorks", $("provider").value === "cloud");
    change("cloud_enabled", false);
    check("cloudDisableReturnsLocal", $("provider").value === "local" && ![...$("executionModel").options].some(option => option.value === "cloud") && cloudConnection.hidden);
    $("settingsTab-translation").click();
    const question = $("settingsPanel-translation").querySelector(".ux-help");
    question.focus();
    check("helpOnKeyboardFocus", !$("contextTooltip").hidden && $("contextTooltip").textContent.length > 20 && question.getAttribute("aria-describedby") === "contextTooltip");
    question.blur();
    question.dispatchEvent(new MouseEvent("mouseenter"));
    check("helpOnHover", !$("contextTooltip").hidden);
    question.click();
    check("helpOnClick", !$("contextTooltip").hidden);
    const bounds = $("contextTooltip").getBoundingClientRect();
    check("helpInsideViewport", bounds.left >= 0 && bounds.right <= innerWidth && bounds.top >= 0 && bounds.bottom <= innerHeight);
    question.dispatchEvent(new MouseEvent("mouseleave"));
    check("helpDismisses", $("contextTooltip").hidden);
    const selected = $("settingsTab-translation");
    selected.dispatchEvent(new KeyboardEvent("keydown", { key: "ArrowDown", bubbles: true, cancelable: true }));
    check("keyboardTabNavigation", $("settingsTab-context").getAttribute("aria-selected") === "true");
    $("settingsTab-files").click();
    change("context", 100);
    await $("saveSettings").onclick();
    check("invalidSettingsStayInDialog", dialog.open && !$("settingsPanel-advanced").hidden);
    change("context", 8192);
    $("settingsTab-files").click();
    change("historyMaxPhrases", 75);
    change("historyMaxSeconds", 0);
    change("processPageSize", 25);
    await $("saveSettings").onclick();
    await tick();
    const snapshot = await request(`state?project=${studioState.project}`);
    const saved = JSON.parse(snapshot.projects.find(project => project.id === studioState.project).settings);
    check("projectSettingsPersisted", !dialog.open && saved.context_before === 9 && saved.use_project_knowledge === false && saved.provider === "local" && saved.cloud_enabled === false);
    const displayPrefs = await request(`process-settings?project=${studioState.project}`);
    check("displaySettingsSavedBySameAction", displayPrefs.max_phrases === 75 && displayPrefs.page_size === 25 && !('run_lines' in saved));
    check("singleOwnerPerControl", ["model", "executionModel", "context", "source_language", "cloud_enabled", "saveSettings"].every(id => document.querySelectorAll(`#${id}`).length === 1));
    $("viewAll").click();
    await tick();
    await loadRows();
    check("textNavigationWorks", studioState.viewMode === "text" && !$("workspaceFiles").hidden && $("rows").querySelectorAll(".record").length === 2);
    const editor = $("rows").querySelector("textarea");
    editor.value = "Несохранённый черновик";
    editor.dispatchEvent(new Event("input", { bubbles: true }));
    $("viewOverview").click();
    check("navigationProtectsUnsavedText", studioState.viewMode === "text" && studioState.dirty.size === 1 && editor.value === "Несохранённый черновик");
    editor.value = "";
    editor.dispatchEvent(new Event("input", { bubbles: true }));
    showView("home");
    check("homeHidesFileTree", $("workspaceFiles").hidden);
    await $("viewKnowledge").onclick();
    check("dictionaryStillWorks", $("knowledgeDialog").open && $("knowledgeDialog").textContent.includes("the captain of Aurora"));
    $("knowledgeDialog").close();
    $("reviewFolder").click();
    await tick();
    $("folderReviewOpen").click();
    check("reviewDialogKeepsProjectControlsSeparate", $("folderReviewDialog").open && !$("folderReviewDialog").contains($("context")));
    $("folderProjectSettings").click();
    check("reviewCanOpenProjectSettings", dialog.open && !$("settingsPanel-translation").hidden);
    $("cancelProjectSettings").click();
    await tick();
    $("folderReviewClose").click();
    showView("home");
    await refresh();
    const records = await request(`records?file=${studioState.snapshot.files[0].id}`);
    check("textsAndQueueUntouched", records.rows.every(row => row.revision === 0 && row.text === "") && JSON.stringify(studioState.snapshot.jobs.map(job => [job.id, job.state, job.provider, job.done])) === originalJobs);
    check("noWorkspaceHorizontalOverflow", document.documentElement.scrollWidth <= innerWidth);
    window.__featureProbe = { passed: true, results };
  } catch (error) {
    window.__featureProbe = { passed: false, error: error.stack, results };
  }
})();
